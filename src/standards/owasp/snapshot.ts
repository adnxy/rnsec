import { readFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

export interface OwaspSource {
  version: string;
  /** null when pinned to a commit instead of a release tag */
  tag: string | null;
  commit: string;
  url: string;
}

export interface MasvsCategory {
  id: string;
  title?: string;
}

export interface MasweEntry {
  title: string;
  /** Full MASVS v2 control IDs, e.g. "MASVS-STORAGE-1" */
  masvs: string[];
  platform: string[];
  cwe?: number[];
}

export interface MastgTestEntry {
  title: string;
  platform: string;
  /** MASWE IDs (all present in the pinned MASWE release) */
  maswe: string[];
}

export interface OwaspSnapshot {
  sources: { masvs: OwaspSource; maswe: OwaspSource; mastg: OwaspSource };
  masvs: {
    categories: MasvsCategory[];
    /** control ID -> statement */
    controls: Record<string, string>;
  };
  maswe: Record<string, MasweEntry>;
  mastg: Record<string, MastgTestEntry>;
}

let cached: OwaspSnapshot | undefined;

/** Loads the vendored OWASP snapshot (generated by scripts/update-owasp-snapshot.mjs). */
export function loadOwaspSnapshot(): OwaspSnapshot {
  if (!cached) {
    cached = JSON.parse(
      readFileSync(resolve(__dirname, "snapshot.json"), "utf-8")
    ) as OwaspSnapshot;
  }
  return cached;
}
