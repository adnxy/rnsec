#!/usr/bin/env node
/**
 * Generates docs/owasp-coverage.md from the central rule -> OWASP mapping (src/standards/owasp/mappings.ts).
 *
 * Usage: npm run docs:owasp   (builds first; this script reads dist/)
 *
 * The control statuses come from buildCoverage(), the same code `rnsec scan --owasp` uses, called with every
 * rule enabled, no findings and every platform present, so the matrix cannot disagree with the CLI.
 * The output is deterministic (sorted rows, no timestamps); tests/owasp-docs.test.mjs fails when the
 * committed file differs from what this script renders.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = (rel) => import(pathToFileURL(resolve(root, "dist", rel)).href);

export const OUT_FILE = resolve(root, "docs/owasp-coverage.md");

// Same groups as registerAllRules() in src/cli/index.ts. tests/owasp-mappings.test.mjs keeps its own copy and
// checks it against `rnsec rules`; a group missing here makes render fail below (a mapped id without a rule).
const GROUPS = [
  ["security/storageScanner.js", "storageRules"],
  ["security/networkScanner.js", "networkRules"],
  ["security/loggingScanner.js", "loggingRules"],
  ["security/configScanner.js", "configRules"],
  ["android/manifestScanner.js", "manifestRules"],
  ["security/authenticationScanner.js", "authenticationRules"],
  ["security/cryptoScanner.js", "cryptoRules"],
  ["react-native/reactNativeScanner.js", "reactNativeRules"],
  ["security/webviewScanner.js", "webviewRules"],
  ["security/secretsScanner.js", "secretsRules"],
  ["security/debugScanner.js", "debugRules"],
  ["android/androidScanner.js", "androidRules"],
  ["ios/iosScanner.js", "iosRules"],
  ["modules/npmScanner.js", "npmVulnerabilityRules"],
  ["security/rnSecurityScanner.js", "rnSecurityRules"],
  ["modules/dependencySourceScanner.js", "dependencySourceRules"],
  ["android/networkSecurityConfigScanner.js", "networkSecurityConfigRules"],
  ["ios/iosPlistExtraScanner.js", "iosPlistExtraRules"],
  ["security/rnExtraScanner.js", "rnExtraRules"],
  ["security/expoConfigScanner.js", "expoConfigRules"],
  ["android/gradleScanner.js", "gradleRules"],
  ["modules/registryConfigScanner.js", "registryConfigRules"],
  ["security/credentialFilesScanner.js", "credentialFileRules"],
];

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const ruleList = (ids) => (ids.length ? ids.map((id) => `\`${id}\``).join(", ") : "none");
const idList = (ids) => (ids.length ? ids.join(", ") : "none");

const STATUS_CLASS = {
  checked: "automated",
  "checked-heuristic": "heuristic only",
  "not-assessed": "manual or dynamic",
};

/** Renders the whole document as a string (no file access besides dist/). */
export async function renderOwaspDocs() {
  const { RULE_STANDARDS, UNMAPPED_RULES } = await dist("standards/owasp/index.js");
  const { loadOwaspSnapshot } = await dist("standards/owasp/snapshot.js");
  const { buildCoverage } = await dist("standards/owasp/coverage.js");
  const snapshot = loadOwaspSnapshot();

  const rules = new Map();
  for (const [file, name] of GROUPS) {
    const group = (await dist(`scanners/${file}`))[name];
    for (const rule of group.rules) rules.set(rule.id, rule);
  }
  for (const id of [...Object.keys(RULE_STANDARDS), ...Object.keys(UNMAPPED_RULES)]) {
    if (!rules.has(id)) throw new Error(`${id} is in the OWASP tables but no rule group in ${import.meta.url} registers it`);
  }
  for (const id of rules.keys()) {
    if (!(id in RULE_STANDARDS) && !(id in UNMAPPED_RULES)) throw new Error(`${id} is in neither RULE_STANDARDS nor UNMAPPED_RULES`);
  }

  const coverage = buildCoverage({
    findings: [],
    ranRuleIds: Object.keys(RULE_STANDARDS),
    platforms: { android: true, ios: true, expo: true },
  });
  const count = (status) => coverage.controls.filter((c) => c.status === status).length;
  const mappedIds = Object.keys(RULE_STANDARDS).sort(cmp);
  const unmappedIds = Object.keys(UNMAPPED_RULES).sort(cmp);
  const { masvs, maswe, mastg } = snapshot.sources;

  const out = [];
  out.push(
    "# OWASP coverage matrix",
    "",
    "<!-- Generated by scripts/generate-owasp-docs.mjs. Do not edit by hand: run `npm run docs:owasp`. -->",
    "",
    "Which OWASP MASVS controls rnsec's automated rules map to. rnsec is static analysis of source, configuration and dependency metadata. " +
      "It does not verify MASVS compliance: a control with automated rules is only *checked* for what those rules look for, and a control without any needs manual or dynamic testing. " +
      "See [OWASP MASVS / MASWE / MASTG](../README.md#owasp-masvs--maswe--mastg) in the README for how `rnsec scan --owasp` reports this per scan.",
    "",
    "Pinned standards (from `src/standards/owasp/snapshot.json`):",
    "",
    `- OWASP MASVS ${masvs.version}`,
    `- OWASP MASWE ${maswe.version}`,
    `- OWASP MASTG ${mastg.version}`,
    "",
    "## MASVS controls",
    "",
    `${coverage.summary.controls} controls: ${count("checked")} automated, ${count("checked-heuristic")} heuristic only, ${count("not-assessed")} manual or dynamic. ` +
      `${mappedIds.length} of ${rules.size} rules are mapped; ${unmappedIds.length} are not (see [Unmapped rules](#unmapped-rules)).`,
    "",
    "Status class:",
    "",
    "- **automated**: at least one mapped rule is not a low-confidence presence/absence heuristic (`checked` in a scan that reports nothing for it)",
    "- **heuristic only**: every mapped rule is a low-confidence heuristic (`checked-heuristic`)",
    "- **manual or dynamic**: no rule maps to the control (`not-assessed`)",
    "",
    "The per-scan statuses `failed` and `not-applicable` depend on the findings and the project's platforms, so they do not appear here.",
    "",
    "| Control | Statement | Automated rule IDs | Status class |",
    "| --- | --- | --- | --- |"
  );
  for (const c of coverage.controls) {
    const status = STATUS_CLASS[c.status];
    if (!status) throw new Error(`unexpected control status ${c.status} for ${c.id}`);
    out.push(`| ${c.id} | ${cell(c.statement)} | ${cell(ruleList(c.rules))} | ${status} |`);
  }

  out.push(
    "",
    "## Rule reference",
    "",
    "Severity is the rule's default; some rules report a lower or higher level depending on context. " +
      "Confidence is how well the rule's check matches the mapped weakness. " +
      "Platform is the platform the rule targets (`cross-platform` applies to every project).",
    "",
    "| Rule ID | Title | Severity | Platform | Confidence | MASVS | MASWE | MASTG | CWE |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"
  );
  for (const id of mappedIds) {
    const s = RULE_STANDARDS[id];
    out.push(
      `| \`${id}\` | ${cell(s.title)} | ${rules.get(id).severity} | ${s.platform.join(", ")} | ${s.confidence} | ` +
        `${idList(s.masvs)} | ${idList(s.maswe)} | ${idList(s.mastg)} | ${idList((s.cwe ?? []).map((n) => `CWE-${n}`))} |`
    );
  }

  out.push(
    "",
    "## Unmapped rules",
    "",
    "These rules have no sound MASVS fit, so their findings carry no OWASP references and they do not count towards any control.",
    "",
    "| Rule ID | Severity | Reason |",
    "| --- | --- | --- |"
  );
  for (const id of unmappedIds) out.push(`| \`${id}\` | ${rules.get(id).severity} | ${cell(UNMAPPED_RULES[id])} |`);

  return out.join("\n") + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const text = await renderOwaspDocs();
  writeFileSync(OUT_FILE, text);
  console.log(`Wrote ${OUT_FILE}`);
}
